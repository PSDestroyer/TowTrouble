using UnityEngine;

namespace TowTrouble
{
    public enum WinchState : byte { Disconnected, Holding, TakingUp, Pulling, Stalled, PayingOut, Minimum, Maximum }

    public struct WinchFrame
    {
        public WinchState State;
        public float Length, Speed, Load;
    }

    // The motor can stop winding; it cannot erase tension caused by vehicle motion.
    public static class RecoveryWinch
    {
        public const float StockForce = 8000f, StockSpeed = 1f;
        public const float MinimumLength = 3.5f, MaximumLength = 20f, PayoutSpeed = 1.7f;

        public static WinchFrame Step(float length, float distance, float separatingSpeed,
            bool reel, bool payout, float maxForce, float maxSpeed, float previousSpeed, float deltaTime)
        {
            maxForce = Mathf.Max(1, maxForce); maxSpeed = Mathf.Max(0, maxSpeed);
            var result = new WinchFrame { Length = length, State = WinchState.Holding };
            if (deltaTime <= 0) return result;
            if (payout && !reel)
            {
                result.Length = Mathf.Min(MaximumLength, length + PayoutSpeed * deltaTime);
                result.Speed = (length - result.Length) / deltaTime;
                result.State = result.Speed < -.001f ? WinchState.PayingOut : WinchState.Maximum;
            }
            else if (reel && !payout)
            {
                // Closing velocity must not let the motor store excessive spring stretch.
                float demand = RecoveryRules.CableDemand(distance, length, Mathf.Max(0, separatingSpeed));
                float load = demand / maxForce;
                float targetSpeed = maxSpeed * Mathf.Clamp01((1 - load) / .75f);
                if (load >= .97f) targetSpeed = 0;
                // Restart gently after the wheel releases; reduce speed immediately under load.
                float rate = Mathf.Min(targetSpeed, Mathf.Max(0, previousSpeed) + maxSpeed * deltaTime / .25f);
                float candidate = Mathf.Max(MinimumLength, length - rate * deltaTime);
                float budgetLength = distance - Mathf.Max(0, maxForce - Mathf.Max(0, separatingSpeed) * RecoveryRules.CableDamping) / RecoveryRules.CableStiffness;
                // Never pay out automatically or cap the force generated by an external jerk.
                result.Length = Mathf.Min(length, Mathf.Max(candidate, budgetLength));
                result.Speed = (length - result.Length) / deltaTime;
                result.State = length <= MinimumLength + .001f ? WinchState.Minimum
                    : result.Speed < .005f ? WinchState.Stalled
                    : result.Length > distance + .02f ? WinchState.TakingUp : WinchState.Pulling;
            }
            result.Load = RecoveryRules.CableDemand(distance, result.Length, separatingSpeed) / maxForce;
            return result;
        }
    }
}
